#!/usr/bin/env python3
"""Generate a .dockerignore for every kit starter that builds an image.

    python tools/build_dockerignore.py          # write them
    python tools/build_dockerignore.py --check  # CI gate

Why this exists: 29 of 35 starters run `COPY . .` and none shipped a
.dockerignore. That means a developer who has done the documented
`cp .env.example .env` bakes their real credentials into the image, and the
whole `.git` directory goes in with them — including any secret that was ever
committed and later removed. For a catalogue whose headline control is "zero
plaintext credentials", the build context was the hole.

Patterns are chosen per stack from marker files, so a Rust kit excludes
`target/` and a Laravel kit excludes `vendor/` and `storage/logs`.
"""

from __future__ import annotations

import argparse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
KITS_DIR = REPO_ROOT / "kits"

HEADER = """# Generated by tools/build_dockerignore.py. Do not edit by hand.
#
# The build context is a security boundary: anything listed here cannot be
# copied into an image even by a broad `COPY . .`.
"""

# Applies to every kit. .env is excluded but .env.example is kept, because the
# image should document its configuration without carrying real values.
BASE = [
    ("Secrets and local configuration", [
        ".env", ".env.*", "!.env.example", "*.pem", "*.key", "*.p12", "*.pfx",
        "secrets/", ".npmrc", ".netrc",
    ]),
    ("Version control — carries deleted secrets in its history", [
        ".git", ".gitignore", ".gitattributes", ".github/",
    ]),
    ("Build recipe itself — never needed inside the image", [
        "Dockerfile", "Dockerfile.*", ".dockerignore", "docker-compose.yml",
        "docker-compose.*.yml",
    ]),
    ("Editor and OS noise", [
        ".vscode/", ".idea/", ".DS_Store", "Thumbs.db", "*.swp",
    ]),
    ("Logs and local databases", [
        "*.log", "logs/", "*.sqlite", "*.sqlite3", "*.sqlite-wal",
        "*.sqlite-shm", "*.db",
    ]),
]

STACKS = {
    "python": (
        ["requirements.txt", "pyproject.toml", "manage.py"],
        ["__pycache__/", "*.py[cod]", ".venv/", "venv/", ".pytest_cache/",
         ".mypy_cache/", ".ruff_cache/", "*.egg-info/", "instance/", ".tox/"],
    ),
    "node": (
        ["package.json"],
        ["node_modules/", ".next/", "dist/", "build/", "coverage/",
         ".turbo/", "*.tsbuildinfo"],
    ),
    "php": (
        ["composer.json"],
        ["vendor/", "storage/logs/", "storage/framework/cache/",
         "storage/framework/sessions/", "storage/framework/views/",
         "bootstrap/cache/", ".phpunit.cache/", ".phpunit.result.cache"],
    ),
    "rust": (["Cargo.toml"], ["target/", "**/*.rs.bk"]),
    "go": (["go.mod"], ["bin/", "vendor/"]),
    "ruby": (["Gemfile"], ["vendor/bundle/", "tmp/", "log/", ".bundle/"]),
    "elixir": (["mix.exs"], ["_build/", "deps/", ".elixir_ls/", "*.ez"]),
}


def stacks_for(starter: Path) -> list[str]:
    found = []
    for name, (markers, _patterns) in STACKS.items():
        if any((starter / m).exists() for m in markers):
            found.append(name)
    return found


def render(starter: Path) -> str:
    lines = [HEADER]
    for title, patterns in BASE:
        lines.append(f"# {title}")
        lines.extend(patterns)
        lines.append("")
    detected = stacks_for(starter)
    for name in detected:
        lines.append(f"# {name} build artifacts and installed dependencies")
        lines.extend(STACKS[name][1])
        lines.append("")
    if not detected:
        lines.append("# No stack marker detected; base rules only.\n")
    return "\n".join(lines).rstrip("\n") + "\n"


def targets() -> list[Path]:
    return sorted(
        p / "starter"
        for p in KITS_DIR.iterdir()
        if (p / "kit.yaml").exists() and (p / "starter" / "Dockerfile").exists()
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any file is missing or stale")
    args = parser.parse_args()

    stale, written = [], 0
    for starter in targets():
        path = starter / ".dockerignore"
        expected = render(starter)
        if args.check:
            if not path.exists():
                stale.append(f"missing {path.relative_to(REPO_ROOT)}")
            elif path.read_text(encoding="utf-8") != expected:
                stale.append(f"stale {path.relative_to(REPO_ROOT)}")
        elif not path.exists() or path.read_text(encoding="utf-8") != expected:
            path.write_text(expected, encoding="utf-8")
            written += 1
            print(f"  wrote {path.relative_to(REPO_ROOT)}  [{', '.join(stacks_for(starter)) or 'base only'}]")

    if args.check:
        if stale:
            print(f"FAIL — {len(stale)} .dockerignore issue(s):")
            for line in stale[:15]:
                print(f"  - {line}")
            print("\nRegenerate with: python tools/build_dockerignore.py")
            return 1
        print(f"PASS — .dockerignore present and current for {len(targets())} kit(s)")
        return 0

    print(f"\n{written} written, {len(targets()) - written} already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
